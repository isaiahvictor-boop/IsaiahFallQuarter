def Add (num1, num2):
    return num1 + num2
sum = Add(9, 10)
print(sum)

def Subtract (num1, num2):
    return num1 - num2
difference = Subtract(15, 6)
print(difference)

def Multiply (num1, num2):
    return num1 * num2
product = Multiply(3, 5)
print(product)

def Division (num1, num2):
    return num1 / num2
quotient = Division(15, 3)
print(quotient)